-- JÁ APLICADO no Supabase (migration documentacao_v1). Idempotente.
--
-- Casa única da documentação por processo (substitui a Página Indexada e
-- absorve o Portal de Processos do Cliente). Navegação pelos Processos
-- Principais do cliente — a MESMA taxonomia do Radar (cockpit.radar_processos).
--
--   doc_tipos           a MATRIZ: que tipos de documento existem, quais são
--                       obrigatórios por processo e até onde cada tipo pode
--                       chegar (nivel_max). É global, vale para todo cliente.
--   doc_series          o documento "lógico" (ex.: Fluxo do Painel de Projetos)
--   doc_versoes         cada arquivo da série: formato + versão + visibilidade.
--                       Só UMA versão vigente por (série, formato).
--   doc_arquivos        o conteúdo (bytea), deduplicado por sha256 — o mesmo
--                       HTML salvo em duas pastas vira um arquivo só.
--   doc_serie_processos liga a série a N processos/ligações do Radar.
--   doc_dispensas       "este processo não precisa deste tipo" (ex.: sem
--                       customização → sem MIT044), com motivo.
--
-- O backend (DATABASE_URL) ignora RLS. A RLS fica ligada SEM política para a
-- chave pública não enxergar nada: documento do cliente não sai por PostgREST.

create table if not exists cockpit.doc_tipos (
  codigo text primary key,
  nome text not null,
  descricao text,
  obrigatorio boolean not null default false,
  nivel_max text not null default 'consultoria' check (nivel_max in ('consultoria','cliente')),
  formatos text[] not null default '{}',
  ordem int not null default 0,
  ativo boolean not null default true
);

create table if not exists cockpit.doc_arquivos (
  id bigint generated by default as identity primary key,
  sha256 text not null unique,
  mime text not null,
  tamanho int not null,
  conteudo bytea not null,
  created_at timestamptz not null default now()
);

create table if not exists cockpit.doc_series (
  id bigint generated by default as identity primary key,
  customer text not null,
  serie text not null,
  tipo text not null references cockpit.doc_tipos(codigo),
  titulo text not null,
  descricao text,
  ordem int not null default 0,
  ativo boolean not null default true,
  criado_por text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (customer, serie)
);

create table if not exists cockpit.doc_versoes (
  id bigint generated by default as identity primary key,
  serie_id bigint not null references cockpit.doc_series(id) on delete cascade,
  formato text not null check (formato in ('html','jpeg','png','svg','pdf','md','txt','link')),
  versao text,
  data_documento date,
  vigente boolean not null default true,
  visibilidade text not null default 'consultoria'
    check (visibilidade in ('rascunho','consultoria','cliente')),
  arquivo_id bigint references cockpit.doc_arquivos(id),
  url_externa text,
  nome_arquivo text,
  origem text,
  nota text,
  publicado_por text,
  publicado_em timestamptz not null default now(),
  liberado_por text,
  liberado_em timestamptz,
  updated_at timestamptz not null default now(),
  check (arquivo_id is not null or url_externa is not null)
);
create unique index if not exists doc_versoes_vigente_uk
  on cockpit.doc_versoes (serie_id, formato) where vigente;
create index if not exists doc_versoes_serie_ix on cockpit.doc_versoes (serie_id);

create table if not exists cockpit.doc_serie_processos (
  serie_id bigint not null references cockpit.doc_series(id) on delete cascade,
  processo_id bigint not null references cockpit.radar_processos(id),
  primary key (serie_id, processo_id)
);

create table if not exists cockpit.doc_dispensas (
  customer text not null,
  processo_id bigint not null references cockpit.radar_processos(id),
  tipo text not null references cockpit.doc_tipos(codigo),
  motivo text,
  dispensado_por text,
  dispensado_em timestamptz not null default now(),
  primary key (customer, processo_id, tipo)
);

