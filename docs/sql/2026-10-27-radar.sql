create table if not exists cockpit.radar_processos (
  id bigint generated by default as identity primary key,
  customer text not null,
  tipo text not null default 'processo' check (tipo in ('processo','ligacao')),
  grupo text not null default 'principal' check (grupo in ('principal','complementar')),
  nome text not null,
  prefixo text,
  origem_id bigint references cockpit.radar_processos(id),
  destino_id bigint references cockpit.radar_processos(id),
  ordem int not null default 0,
  ativo boolean not null default true,
  slug_fluxo text,
  created_at timestamptz not null default now(),
  unique (customer, tipo, nome),
  check (tipo = 'processo' or (origem_id is not null and destino_id is not null))
);

create table if not exists cockpit.radar_itens (
  id bigint generated by default as identity primary key,
  customer text not null default '000348D0',
  codigo text,
  tipo text not null default 'definicao' check (tipo in ('definicao','atividade')),
  processo_id bigint not null references cockpit.radar_processos(id),
  ligacao_id bigint references cockpit.radar_processos(id),
  titulo text not null,
  contexto text,
  dono_lado text not null default 'TOTVS' check (dono_lado in ('TOTVS','DIGITRO','AMBOS')),
  dono_nome text,
  status text not null default 'aberta' check (status in ('aberta','em_discussao','decidida','implementada','cancelada')),
  prioridade text not null default 'media' check (prioridade in ('alta','media','baixa')),
  bloqueia text,
  prazo date,
  decisao text,
  decidida_em date,
  task_ids text[] not null default '{}',
  mit006_ref text,
  aberta_em date not null default current_date,
  ultima_evidencia_em timestamptz,
  created_by text, updated_by text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (customer, codigo)
);

create table if not exists cockpit.radar_evidencias (
  id bigint generated by default as identity primary key,
  item_id bigint not null references cockpit.radar_itens(id) on delete cascade,
  fonte text not null check (fonte in ('email','transcricao','drive_doc','tasks_status','tasks_ocorrencia','reuniao','manual')),
  fonte_ref text not null,
  titulo text, autor text, ocorrido_em timestamptz, link text, trecho text,
  created_by text,
  created_at timestamptz not null default now(),
  unique (item_id, fonte, fonte_ref)
);

create table if not exists cockpit.radar_execucoes (
  id bigint generated by default as identity primary key,
  customer text not null default '000348D0',
  iniciada_em timestamptz not null default now(),
  finalizada_em timestamptz,
  cursores jsonb not null default '{}'::jsonb,
  fontes_lidas jsonb not null default '{}'::jsonb,
  propostas_geradas int not null default 0,
  resumo text, erro text
);

create table if not exists cockpit.radar_propostas (
  id bigint generated by default as identity primary key,
  customer text not null default '000348D0',
  item_id bigint references cockpit.radar_itens(id) on delete cascade,
  acao text not null check (acao in ('criar','atualizar','mudar_status','adicionar_evidencia','vincular_task')),
  payload jsonb not null default '{}'::jsonb,
  evidencias jsonb not null default '[]'::jsonb,
  justificativa text,
  confianca numeric(3,2) check (confianca between 0 and 1),
  situacao text not null default 'pendente' check (situacao in ('pendente','aprovada','rejeitada','aplicada')),
  execucao_id bigint references cockpit.radar_execucoes(id) on delete set null,
  revisado_por text, revisado_em timestamptz, motivo_rejeicao text,
  created_at timestamptz not null default now()
);
create unique index if not exists radar_prop_dedup_idx
  on cockpit.radar_propostas (customer, coalesce(item_id, 0), acao, md5(payload::text))
  where situacao = 'pendente';

