-- Aba Tributos (Configurador de Tributos — FISA170) — 30/10/2026
-- Spec: docs/specs/2026-10-30-aba-tributos.md
-- Uma linha por coleta de UMA base. A coleta é faseada (a função da Vercel
-- morre em 60 s): a 1ª chamada grava `meta` (dicionário + quantidades) e a
-- lista `pendentes`; as seguintes juntam o conteúdo em `dados` (jsonb || jsonb)
-- até `pendentes` esvaziar. O backend guarda as 6 últimas por base.
-- Pode rodar ANTES do deploy (tabela nova; o código antigo não a conhece).

create table if not exists cockpit.trib_coletas (
  id bigint generated by default as identity primary key,
  customer text not null,
  ambiente text not null check (ambiente in ('producao','teste')),
  iniciado_em timestamptz not null default now(),
  concluido_em timestamptz,
  status text not null default 'coletando' check (status in ('coletando','ok','parcial','erro')),
  meta jsonb not null default '{}'::jsonb,
  dados jsonb not null default '{}'::jsonb,
  pendentes text[] not null default '{}',
  chamadas int not null default 0,
  duracao_ms int,
  environment text,
  sufixo text,
  erro text,
  disparado_por text
);
create index if not exists trib_coletas_cli_amb on cockpit.trib_coletas (customer, ambiente, iniciado_em desc);
comment on table cockpit.trib_coletas is
  'Aba Tributos: retrato do Configurador de Tributos (F2x/CIx/CJx) por base, lido pela TSCMONITREST.';

-- Mesmo padrão das outras tabelas do cockpit: RLS ligado sem policy; o Flask
-- (DATABASE_URL) ignora RLS e é o único que lê/grava.
alter table cockpit.trib_coletas enable row level security;
