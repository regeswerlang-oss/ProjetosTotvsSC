-- 6) A RPC de aprovação passa a levar os campos de cliente
create or replace function cockpit.radar_aplicar_proposta(p_id bigint, p_usuario text)
 returns bigint language plpgsql set search_path to '' as $function$
declare
  p  cockpit.radar_propostas%rowtype;
  r  cockpit.radar_itens%rowtype;
  n  cockpit.radar_itens%rowtype;
  v_item bigint;
begin
  select * into p from cockpit.radar_propostas where id = p_id for update;
  if not found then raise exception 'Proposta % não encontrada', p_id; end if;
  if p.situacao <> 'pendente' then raise exception 'Proposta % já está %', p_id, p.situacao; end if;

  if p.acao = 'criar' then
    n := jsonb_populate_record(null::cockpit.radar_itens, p.payload);
    insert into cockpit.radar_itens
      (customer, tipo, processo_id, ligacao_id, titulo, contexto, dono_lado, dono_nome, status,
       prioridade, bloqueia, prazo, decisao, decidida_em, task_ids, mit006_ref, aberta_em,
       visivel_cliente, texto_cliente, retorno_cliente, created_by, updated_by)
    values
      (coalesce(n.customer, p.customer), coalesce(n.tipo,'definicao'), n.processo_id, n.ligacao_id, n.titulo, n.contexto,
       coalesce(n.dono_lado,'TOTVS'), n.dono_nome, coalesce(n.status,'aberta'), coalesce(n.prioridade,'media'),
       n.bloqueia, n.prazo, n.decisao, n.decidida_em, coalesce(n.task_ids,'{}'), n.mit006_ref, coalesce(n.aberta_em, current_date),
       coalesce(n.visivel_cliente,false), n.texto_cliente, n.retorno_cliente, p_usuario, p_usuario)
    returning id into v_item;
  else
    v_item := p.item_id;
    select * into r from cockpit.radar_itens where id = v_item for update;
    if not found then raise exception 'Item % da proposta % não existe', v_item, p_id; end if;
    if p.acao in ('atualizar','mudar_status','vincular_task') then
      n := jsonb_populate_record(r, p.payload - 'id' - 'codigo' - 'customer' - 'created_at' - 'created_by');
      if p.acao = 'vincular_task' then
        n.task_ids := (select array(select distinct unnest(r.task_ids || n.task_ids)));
      end if;
      if n.status = 'decidida' and n.decidida_em is null then n.decidida_em := current_date; end if;
      update cockpit.radar_itens set
        tipo = n.tipo, processo_id = n.processo_id, ligacao_id = n.ligacao_id, titulo = n.titulo,
        contexto = n.contexto, dono_lado = n.dono_lado, dono_nome = n.dono_nome, status = n.status,
        prioridade = n.prioridade, bloqueia = n.bloqueia, prazo = n.prazo, decisao = n.decisao,
        decidida_em = n.decidida_em, task_ids = n.task_ids, mit006_ref = n.mit006_ref,
        visivel_cliente = n.visivel_cliente, texto_cliente = n.texto_cliente, retorno_cliente = n.retorno_cliente,
        updated_by = p_usuario
      where id = v_item;
    end if;
  end if;

  insert into cockpit.radar_evidencias (item_id, fonte, fonte_ref, titulo, autor, ocorrido_em, link, trecho, created_by)
  select v_item, e.fonte, e.fonte_ref, e.titulo, e.autor, e.ocorrido_em, e.link, e.trecho, p_usuario
    from jsonb_to_recordset(p.evidencias)
         as e(fonte text, fonte_ref text, titulo text, autor text, ocorrido_em timestamptz, link text, trecho text)
  on conflict (item_id, fonte, fonte_ref) do nothing;

  update cockpit.radar_propostas
     set situacao = 'aplicada', item_id = v_item, revisado_por = p_usuario, revisado_em = now()
   where id = p_id;
  return v_item;
end $function$;

-- vw_radar_itens precisa expor as colunas novas (i.* não é dinâmico em view)
create or replace view cockpit.vw_radar_itens with (security_invoker = true) as
 select i.id, i.customer, i.codigo, i.tipo, i.processo_id, i.ligacao_id, i.titulo, i.contexto,
        i.dono_lado, i.dono_nome, i.status, i.prioridade, i.bloqueia, i.prazo, i.decisao, i.decidida_em,
        i.task_ids, i.mit006_ref, i.aberta_em, i.ultima_evidencia_em, i.created_by, i.updated_by,
        i.created_at, i.updated_at,
        pr.nome as processo_nome, pr.grupo as processo_grupo, pr.ordem as processo_ordem, pr.slug_fluxo,
        lg.nome as ligacao_nome,
        (current_date - i.aberta_em) as dias_aberta,
        case when i.ultima_evidencia_em is null then current_date - i.aberta_em
             else current_date - i.ultima_evidencia_em::date end as dias_sem_evidencia,
        (select count(*) from cockpit.radar_evidencias e where e.item_id = i.id) as n_evidencias,
        (select count(*) from cockpit.radar_propostas p where p.item_id = i.id and p.situacao = 'pendente') as propostas_pendentes,
        i.visivel_cliente, i.texto_cliente, i.retorno_cliente, pr.prefixo as processo_prefixo
   from cockpit.radar_itens i
   join cockpit.radar_processos pr on pr.id = i.processo_id
   left join cockpit.radar_processos lg on lg.id = i.ligacao_id;
