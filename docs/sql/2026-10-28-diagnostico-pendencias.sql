-- 2) Matriz de diagnóstico: catálogo de verificações por processo × camada
create table if not exists cockpit.diag_checks (
  customer text not null,
  check_id text not null,                       -- ex.: CTB-K01
  processo_prefixo text not null,               -- casa com radar_processos.prefixo
  camada text not null check (camada in ('cadastro','movimento','contabilizacao','fluxo')),
  titulo text not null,
  pergunta text,                                 -- a pergunta de negócio que o número responde
  tipo text not null default 'sql' check (tipo in ('sql','manual','monitcad')),
  sql text,                                      -- Oracle, {SB1} = SB1+sufixo; devolve VALOR;TOTAL;AMOSTRA
  regra jsonb not null default '{"modo":"zero"}'::jsonb,
  ambientes text[] not null default '{producao,teste}',
  impeditivo boolean not null default false,     -- impede protótipo/virada se vermelho
  marco text,                                    -- prototipo_0911 | carga_1911 | ciclo2_3011 | virada
  radar_codigos text[] not null default '{}',
  mit006_ids text[] not null default '{}',
  visivel_cliente boolean not null default true,
  responsavel_lado text check (responsavel_lado in ('TOTVS','DIGITRO','AMBOS')),
  status_manual text check (status_manual in ('verde','amarelo','vermelho','cinza')),
  nota text,
  avaliado_por text, avaliado_em timestamptz,
  ordem int not null default 0,
  ativo boolean not null default true,
  updated_at timestamptz not null default now(),
  primary key (customer, check_id)
);

create table if not exists cockpit.diag_execucoes (
  id bigint generated by default as identity primary key,
  customer text not null,
  ambiente text not null,
  iniciada_em timestamptz not null default now(),
  finalizada_em timestamptz,
  ok int not null default 0,
  falhas int not null default 0,
  disparado_por text,
  erro text
);

create table if not exists cockpit.diag_resultados (
  id bigint generated by default as identity primary key,
  execucao_id bigint references cockpit.diag_execucoes(id) on delete cascade,
  customer text not null,
  check_id text not null,
  ambiente text not null,
  coletado_em timestamptz not null default now(),
  valor numeric, total numeric,
  status text not null check (status in ('verde','amarelo','vermelho','cinza','info')),
  amostra text, erro text, ms int
);
create index if not exists diag_res_ult_idx on cockpit.diag_resultados (customer, check_id, ambiente, coletado_em desc);

create or replace view cockpit.vw_diag_ultimo with (security_invoker = true) as
select distinct on (r.customer, r.check_id, r.ambiente) r.*
  from cockpit.diag_resultados r
 order by r.customer, r.check_id, r.ambiente, r.coletado_em desc;

